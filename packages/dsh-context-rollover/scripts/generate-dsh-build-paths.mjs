/** Map public host package exports to built declarations for plugin-only emit. */
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { dirname, isAbsolute, join, relative, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..')
if (!process.env.DSH_CHECKOUT_DIR || !isAbsolute(process.env.DSH_CHECKOUT_DIR)) {
  throw new Error('DSH_CHECKOUT_DIR must be an absolute public DSH checkout path')
}
if (process.argv.length > 2) throw new Error('generate-dsh-build-paths takes no arguments; use the root public baseline')
const checkoutDir = resolve(process.env.DSH_CHECKOUT_DIR)

function withDotSlash(path) {
  const normalized = path.split(String.fromCharCode(92)).join('/')
  return normalized.startsWith('.') ? normalized : `./${normalized}`
}

function* packageDirs() {
  const vendors = join(checkoutDir, 'vendor')
  for (const vendor of readdirSync(vendors, { withFileTypes: true })) {
    if (vendor.isDirectory()) yield join(vendors, vendor.name)
  }
  const packages = join(checkoutDir, 'packages')
  for (const group of readdirSync(packages, { withFileTypes: true })) {
    if (!group.isDirectory()) continue
    const groupDir = join(packages, group.name)
    for (const pkg of readdirSync(groupDir, { withFileTypes: true })) {
      if (pkg.isDirectory()) yield join(groupDir, pkg.name)
    }
  }
}

const paths = {}
for (const dir of packageDirs()) {
  const manifestPath = join(dir, 'package.json')
  if (!existsSync(manifestPath)) continue
  const manifest = JSON.parse(readFileSync(manifestPath, 'utf8'))
  if (typeof manifest.name !== 'string' || !manifest.name.startsWith('@deepseek-ai/')) continue
  for (const [subpath, target] of Object.entries(manifest.exports ?? {})) {
    const types = typeof target === 'string' ? target : target?.types
    if (typeof types !== 'string' || !types.endsWith('.d.ts') || !existsSync(resolve(dir, types))) continue
    const key = subpath === '.' ? manifest.name : `${manifest.name}/${subpath.replace(/^\.\//, '')}`
    paths[key] = [withDotSlash(relative(projectRoot, resolve(dir, types)))]
  }
}

const ownManifest = JSON.parse(readFileSync(join(projectRoot, 'package.json'), 'utf8'))
for (const peer of Object.keys(ownManifest.peerDependencies)) {
  if (paths[peer] === undefined) throw new Error(`Public host declarations missing for ${peer}; build DSH_CHECKOUT_DIR first`)
}
writeFileSync(resolve(projectRoot, 'tsconfig.build-paths.json'), `${JSON.stringify({
  _comment: 'Generated by scripts/generate-dsh-build-paths.mjs — do not edit.',
  extends: withDotSlash(relative(projectRoot, join(checkoutDir, 'tsconfig.base.json'))),
  compilerOptions: { paths },
}, null, 2)}\n`)
console.log(`generated tsconfig.build-paths.json (${Object.keys(paths).length} entries)`)
